motor1.set_speed_pid_constants(4e-2, 4e-4, 3e-2)
motor1.set_position_pid_constants(275, 0, 0)
motor1.set_position_region_boundary(250000)
motor1.configure_operating_mode_and_sensor(3, 1)
motor1.configure_command_mode(12)
